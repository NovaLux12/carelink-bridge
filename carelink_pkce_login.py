#!/usr/bin/env python3
"""CareLink PKCE login helper — replaces `npm run login`'s terminal-paste path.

Two steps so the code challenge and the token exchange are generated by the same
process run, with the verifier persisted between them:

  python3 carelink_pkce_login.py start   -> prints the authorize URL, saves verifier+state
  python3 carelink_pkce_login.py finish '<redirect url or bare code>'
                                          -> exchanges for tokens, writes logindata.json

Why this exists: `npm run login` strategy 3 asks for the redirect URL on stdin, and
the Auth0/CareLink login page expires its session while you are finding it. Doing
the exchange here keeps it to one command with no waiting between.
"""

import base64
import hashlib
import json
import os
import secrets
import sys
import urllib.error
import urllib.parse
import urllib.request

AUTHZ = "https://carelink-login.minimed.eu/authorize"
TOKEN = "https://carelink-login.minimed.eu/oauth/token"
DISCOVERY = "https://clcloud.minimed.eu/connect/carepartner/v13/discover/android/3.6"
CLIENT_ID = "PeAhkbhQWlQRxJiQxWfcFBiGus1lxfe9"  # public, embedded in the CarePartner EU app
AUDIENCE = "carepartner.patient.ous"
SCOPE = "profile openid offline_access"

# ⚠ The redirect URI is "com.medtronic.carepartner:/sso" — ONE slash, not "://".
# Auth0 answers a near-miss with `Callback URL mismatch`, which reads like a
# client-id problem and sends you looking in the wrong place. Read it from
# Medtronic's own SSO config instead of hardcoding it, so it cannot drift.
FALLBACK_REDIRECT = "com.medtronic.carepartner:/sso"


def resolve_redirect_uri() -> str:
    """Read redirect_uri from the live EU Auth0 SSO config; fall back if offline."""
    try:
        with urllib.request.urlopen(DISCOVERY, timeout=20) as resp:
            disc = json.loads(resp.read())
        # CP[] carries US, EU, CLINICAL in that order.
        sso_url = None
        for region in disc.get("CP", []):
            if "minimed.eu" in region.get("Auth0SSOConfiguration", ""):
                sso_url = region["Auth0SSOConfiguration"]
                break
        if not sso_url:
            return FALLBACK_REDIRECT
        with urllib.request.urlopen(sso_url, timeout=20) as resp:
            sso = json.loads(resp.read())
        return sso["client"]["redirect_uri"]
    except Exception as exc:  # network/parse — the fallback is correct today
        print(f"warn: could not read SSO config ({exc}); using known value",
              file=sys.stderr)
        return FALLBACK_REDIRECT


REDIRECT = resolve_redirect_uri()

HERE = os.path.dirname(os.path.abspath(__file__))
VERIFIER_FILE = os.path.join(HERE, ".pkce-verifier")
LOGINDATA = os.path.join(HERE, "logindata.json")


def b64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).decode().rstrip("=")


def start() -> int:
    verifier = b64url(secrets.token_bytes(32))
    challenge = b64url(hashlib.sha256(verifier.encode()).digest())
    state = b64url(secrets.token_bytes(16))
    with open(VERIFIER_FILE, "w") as fh:
        json.dump({"verifier": verifier, "state": state}, fh)
    os.chmod(VERIFIER_FILE, 0o600)

    params = {
        "client_id": CLIENT_ID,
        "response_type": "code",
        "scope": SCOPE,
        "audience": AUDIENCE,
        "redirect_uri": REDIRECT,
        "code_challenge": challenge,
        "code_challenge_method": "S256",
        "state": state,
    }
    print(AUTHZ + "?" + urllib.parse.urlencode(params))
    return 0


def finish(pasted: str) -> int:
    if not os.path.exists(VERIFIER_FILE):
        print("error: no verifier — run `start` first", file=sys.stderr)
        return 2
    saved = json.load(open(VERIFIER_FILE))

    # Accept a full redirect URL, a query string, or a bare code.
    code = None
    if "code=" in pasted:
        qs = urllib.parse.urlparse(pasted).query or pasted.split("?", 1)[-1]
        code = urllib.parse.parse_qs(qs).get("code", [None])[0]
    elif pasted.strip() and " " not in pasted.strip() and len(pasted.strip()) > 20:
        code = pasted.strip()
    if not code:
        print(f"error: no code= found in input ({len(pasted)} chars)", file=sys.stderr)
        return 2

    body = urllib.parse.urlencode({
        "grant_type": "authorization_code",
        "client_id": CLIENT_ID,
        "code": code,
        "redirect_uri": REDIRECT,
        "code_verifier": saved["verifier"],
    }).encode()

    req = urllib.request.Request(
        TOKEN, data=body,
        headers={"Content-Type": "application/x-www-form-urlencoded"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            payload = json.loads(resp.read())
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode(errors="replace")
        print(f"error: token exchange failed HTTP {exc.code}: {detail}", file=sys.stderr)
        if "invalid_grant" in detail:
            print("hint: the authorization code is single-use and short-lived — "
                  "run `start` again and complete the login in one go.", file=sys.stderr)
        return 1

    access = payload.get("access_token")
    refresh = payload.get("refresh_token")
    if not access or not refresh:
        print(f"error: response missing tokens: keys={sorted(payload)}", file=sys.stderr)
        return 1

    login_data = {
        "access_token": access,
        "refresh_token": refresh,
        "scope": payload.get("scope", SCOPE),
        "client_id": CLIENT_ID,
        "token_url": TOKEN,
        "audience": AUDIENCE,
    }
    tmp = LOGINDATA + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(login_data, fh, indent=2)
    os.chmod(tmp, 0o600)
    os.replace(tmp, LOGINDATA)
    os.remove(VERIFIER_FILE)

    print(f"ok: logindata.json written ({os.path.getsize(LOGINDATA)} bytes, mode 600)")
    print(f"    token expires in {payload.get('expires_in', '?')} s; "
          f"scope={login_data['scope']}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in ("start", "finish"):
        print(__doc__)
        sys.exit(2)
    if sys.argv[1] == "start":
        sys.exit(start())
    if len(sys.argv) < 3:
        print("error: finish needs the redirect URL or code", file=sys.stderr)
        sys.exit(2)
    sys.exit(finish(sys.argv[2]))
